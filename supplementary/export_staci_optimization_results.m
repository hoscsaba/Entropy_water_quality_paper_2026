function export_staci_optimization_results(output_file)
%EXPORT_STACI_OPTIMIZATION_RESULTS Compact audit table for the new six GAs.
root = fileparts(fileparts(mfilename('fullpath')));
if nargin < 1
    output_file = fullfile(root, 'supplementary', 'results', ...
        'staci_constrained_optimization.csv');
end
networks = ["tanyimboh_templeman", "anytown", "balerma"];
objectives = ["chlorine_concentration", "chlorine_entropy"];
rows = cell(numel(networks) * numel(objectives), 11);
line = 0;
for network = networks
    folder = fullfile(root, 'networks', network, 'results_staci_constrained');
    for objective = objectives
        saved = load(fullfile(folder, objective + ".mat"), 'result');
        result = saved.result;
        line = line + 1;
        rows(line, :) = {network, objective, result.optimizer_value, ...
            result.metrics.cost, result.metrics.hydraulic_entropy, ...
            result.metrics.chlorine_concentration, ...
            result.metrics.chlorine_entropy, ...
            result.metrics.minimum_consumer_chlorine_mgL, ...
            result.max_constraint_violation, ...
            result.elapsed_time_seconds, result.incumbent_source};
    end
end
table_out = cell2table(rows, 'VariableNames', ...
    {'network','objective','optimizer_value','cost','hydraulic_entropy', ...
     'chlorine_concentration','chlorine_entropy', ...
     'minimum_consumer_chlorine_mgL','max_constraint_violation', ...
     'elapsed_time_s','incumbent_source'});
if ~isfolder(fileparts(output_file)), mkdir(fileparts(output_file)); end
writetable(table_out, output_file);
disp(table_out);
end
