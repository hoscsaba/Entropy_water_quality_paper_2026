function output=summarize_balerma_protected_connector_stress(result_dir)
%SUMMARIZE_BALERMA_PROTECTED_CONNECTOR_STRESS Re-score saved PDA outages.
% All four reservoirs remain connected in the first state. In the second,
% R44 is isolated by its sole connector P188. No direct reservoir connector
% is eligible as the additional single-pipe failure in either state.
% Existing scenario results are filtered; no hydraulic or quality solve runs.
if nargin<1 || isempty(result_dir)
    result_dir=fullfile(fileparts(mfilename('fullpath')), ...
        'results_staci_uniform_0p1_64in_sourceentry_v4');
end
network_dir=fileparts(mfilename('fullpath'));
protected=["5","338","194","223","188","51"];
validate_connectors(fullfile(network_dir,'input','network_original.inp'), ...
    protected);
out=fullfile(result_dir,'protected_connector_stress');
if ~isfolder(out),mkdir(out);end

raw=readtable(fullfile(result_dir,'pda_service_scenarios.csv'), ...
    'TextType','string');
eligible=~ismember(string(raw.FailedLinkID),protected);
scenarios=raw(eligible,:);
assert(height(raw)==6*2*454 && height(scenarios)==6*2*448);
original=readtable(fullfile(result_dir,'pda_service_six.csv'), ...
    'TextType','string');
service_rows=cell(height(original),1);
vulnerability_rows=cell(height(original),1);
states=["all_four","R44_unavailable"];
for j=1:height(original)
    objective=string(original.Objective(j));
    label=string(original.Topology(j));
    cases=scenarios(string(scenarios.Objective)==objective,:);
    assert(height(cases)==896 && all(~cases.Nonconvergent) && ...
        all(ismember(states,string(cases.ReservoirAvailability))));
    for state=states
        subset=cases(string(cases.ReservoirAvailability)==state,:);
        assert(height(subset)==448 && ...
            numel(unique(string(subset.FailedLinkID)))==448);
    end
    water=double(cases.DeliveredDemandFraction);
    chlorine=double(cases.QualityCompliantDemandFraction);
    assert(all(isfinite([water;chlorine])) && ...
        all(chlorine<=water+1e-10));
    service_rows{j}=table(objective,label,height(cases), ...
        mean(water),min(water),mean(chlorine),min(chlorine), ...
        nnz(cases.EpanetFallback), ...
        'VariableNames',{'Objective','Topology','FailureCases', ...
        'MeanDeliveredDemandFraction','WorstDeliveredDemandFraction', ...
        'MeanQualityCompliantDemandFraction', ...
        'WorstQualityCompliantDemandFraction','EpanetFallbackCases'});
    n_worst=ceil(0.1*height(cases));
    water_deficit=sort(1-water,'descend');
    joint_deficit=sort(1-chlorine,'descend');
    vulnerability_rows{j}=table(objective,label,height(cases), ...
        n_worst,100*mean(water_deficit(1:n_worst)), ...
        100*mean(joint_deficit(1:n_worst)), ...
        100*mean(water<0.95),100*mean(water-chlorine), ...
        'VariableNames',{'Objective','Topology','FailureCases', ...
        'WorstTenPercentCount','WorstTenPercentWaterDeficitPct', ...
        'WorstTenPercentJointDeficitPct','Below95WaterPct', ...
        'MeanChlorineOnlyLossPct'});
end
service=vertcat(service_rows{:});
vulnerability=vertcat(vulnerability_rows{:});
writetable(scenarios,fullfile(out,'pda_service_scenarios.csv'));
writetable(service,fullfile(out,'pda_service_six.csv'));
writetable(vulnerability,fullfile(out,'pda_vulnerability_summary.csv'));
writetable(table(protected(:),'VariableNames',{'PipeID'}), ...
    fullfile(out,'protected_source_connectors.csv'));

saved=load(fullfile(result_dir,'pareto_cost_branch_hop_top90.mat'), ...
    'result');
designs=double(saved.result.designs);
selected=readtable(fullfile(result_dir,'pareto_selected20_indices.csv'));
ids=double(selected.ArchiveIndex(:));
assert(numel(ids)==20 && numel(unique(ids))==20);
pooled_rows=cell(numel(ids),1);
all_four_rows=cell(numel(ids),1);
for k=1:numel(ids)
    id=ids(k);
    file=fullfile(result_dir,'pareto_failure_replay_r44', ...
        'checkpoints',sprintf('point_%04d.mat',id));
    item=load(file,'diameters','all_cases');
    assert(isequal(double(item.diameters(:)'),designs(id,:)), ...
        'Stale Pareto checkpoint %d',id);
    all_cases=item.all_cases;
    assert(height(all_cases)==908 && all(~all_cases.Nonconvergent));
    cases=all_cases(~ismember(string(all_cases.FailedLinkID), ...
        protected),:);
    assert(height(cases)==896 && ...
        nnz(string(cases.ReservoirAvailability)=="all_four")==448 && ...
        nnz(string(cases.ReservoirAvailability)=="R44_unavailable")==448);
    pooled_rows{k}=pareto_row(cases,id,saved.result);
    all_four_rows{k}=pareto_row(cases( ...
        string(cases.ReservoirAvailability)=="all_four",:), ...
        id,saved.result);
end
pareto_pooled=sortrows(vertcat(pooled_rows{:}),'ArchiveIndex');
pareto_all_four=sortrows(vertcat(all_four_rows{:}),'ArchiveIndex');
pooled_dir=fullfile(out,'pareto_pooled');
four_dir=fullfile(out,'pareto_all_four');
if ~isfolder(pooled_dir),mkdir(pooled_dir);end
if ~isfolder(four_dir),mkdir(four_dir);end
writetable(pareto_pooled,fullfile(pooled_dir, ...
    'pareto_failure_service.csv'));
writetable(pareto_all_four,fullfile(four_dir, ...
    'pareto_failure_service.csv'));
output=struct('service',service,'vulnerability',vulnerability, ...
    'pareto_pooled',pareto_pooled, ...
    'pareto_all_four',pareto_all_four, ...
    'protected_pipe_ids',protected);
fprintf(['Protected-source replay summarized: 6 designs and 20 Pareto ' ...
    'designs, 448 failures per source state.\n']);
end

function row=pareto_row(cases,id,archive)
water=100*double(cases.DeliveredDemandFraction);
chlorine=100*double(cases.QualityCompliantDemandFraction);
[water_worst,wi]=min(water);[cl_worst,ci]=min(chlorine);
row=table(id,archive.cost(id),archive.branch_hop_entropy(id), ...
    mean(water),water_worst,mean(chlorine),cl_worst, ...
    string(cases.FailedLinkID(wi)), ...
    string(cases.ReservoirAvailability(wi)), ...
    string(cases.FailedLinkID(ci)), ...
    string(cases.ReservoirAvailability(ci)),height(cases), ...
    nnz(cases.Nonconvergent),nnz(cases.SolverToleranceFallback), ...
    nnz(cases.EpanetFallback), ...
    'VariableNames',{'ArchiveIndex','Cost','BranchHopEntropy', ...
    'WaterMeanPct','WaterWorstPct','ClMeanPct','ClWorstPct', ...
    'WaterWorstPipe','WaterWorstAvailability','ClWorstPipe', ...
    'ClWorstAvailability','FailureCases','NonconvergentScenarios', ...
    'ToleranceFallbackCases','EpanetFallbackCases'});
end

function validate_connectors(input_file,protected)
lines=splitlines(string(fileread(input_file)));
section="";found=strings(0,1);
reservoirs=["38","43","44","88"];
for raw_line=lines(:)'
    line=strip(extractBefore(raw_line+";",";"));
    if startsWith(line,"[")
        section=upper(line);continue
    end
    if section~="[PIPES]" || strlength(line)==0,continue;end
    parts=split(line);
    if numel(parts)<3,continue;end
    if ismember(parts(2),reservoirs) || ...
            ismember(parts(3),reservoirs)
        found(end+1,1)=parts(1); %#ok<AGROW>
    end
end
assert(isequal(sort(found),sort(protected(:))), ...
    'Reservoir connectors in the original INP changed');
end
