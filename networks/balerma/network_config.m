function cfg = network_config(network_dir)
%NETWORK_CONFIG Reproducible settings for the Balerma benchmark.

if nargin == 0
    network_dir = fileparts(mfilename('fullpath'));
end
project_root = fileparts(fileparts(network_dir));

cfg.id = 'balerma';
cfg.inp_file = fullfile(network_dir, 'input', 'network_original.inp');
cfg.results_dir = fullfile(network_dir, 'results_staci');
cfg.figures_dir = fullfile(network_dir, 'figures_staci');
cfg.runtime_dir = fullfile(network_dir, 'runtime');
cfg.toolkit_dir = fullfile(project_root, 'third_party', ...
    'epanet_matlab_toolkit');
toolkit_override = getenv('WDS_EPANET_TOOLKIT');
if ~isempty(toolkit_override)
    cfg.toolkit_dir = toolkit_override;
end
native_library = fullfile(project_root, 'third_party', ...
    'epanet22_arm64', 'libepanet2');
cfg.toolkit_patch_dir = fullfile(project_root, 'third_party', ...
    'epanet_matlab_toolkit_patch');
if ismac && isfile(strcat(native_library, '.dylib'))
    cfg.epanet_library = native_library;
else
    cfg.epanet_library = '';
end

cfg.design_link_ids = read_section_ids(cfg.inp_file, 'PIPES');
cfg.fixed_link_diameters = struct();
cfg.entropy_excluded_link_ids = {};
cfg.minimum_diameter = 10;
cfg.maximum_diameter = 500;
cfg.numeric_tolerance = 1e-9;
cfg.diameter_to_inches = 0.0393700787;
cfg.length_cost_factor = 1;

cfg.pressure_node_ids = read_section_ids(cfg.inp_file, 'JUNCTIONS');
cfg.quality_node_ids = cfg.pressure_node_ids;
cfg.minimum_pressure = 10;
cfg.maximum_pressure = 70;
cfg.pressure_to_head = 1;

cfg.cost_coefficient = 230;
cfg.cost_exponent = 0.48;
cfg.quality_duration_hours = 48;
% EPANET previously clamped the requested 48 h quality step to the 1 h
% hydraulic step. State the effective setting explicitly for reproducibility.
cfg.quality_step_hours = 1;
cfg.bulk_reaction_coefficient = -1;
cfg.source_chlorine = 1;
cfg.source_node_ids = read_section_ids(cfg.inp_file, 'RESERVOIRS');

% Every physical Balerma pipe is failed once; all 443 junctions are assessed.
cfg.stress.failed_link_ids = cfg.design_link_ids;
cfg.stress.node_ids = cfg.pressure_node_ids;
cfg.stress.minimum_chlorine = 0.2;

cfg.objectives = {'cost','hydraulic_entropy','chlorine_concentration', ...
    'chlorine_entropy','todini'};

% The same 100-member GA framework; Balerma has its own wall-time ceiling.
cfg.ga.random_seed = 1993;
cfg.ga.population_size = 100;
cfg.ga.max_generations = 10000;
cfg.ga.max_stall_generations = 150;
cfg.ga.function_tolerance = 1e-6;
cfg.ga.constraint_tolerance = 5e-5;
cfg.ga.use_hybrid_patternsearch = false;
cfg.ga.display = 'iter';

% Nested ranked-subset study. Four points retain the 0--9.91% span while
% keeping each of the four objectives within a practical two-hour budget.
% Each point has an independent cache file, so adding larger K values later
% does not repeat completed calculations.
cfg.ranking.perturbation_fraction = 0.10;
cfg.ranking.k_values = [0, 5, 20, 45];
cfg.ranking.max_generations = 100;
cfg.ranking.max_stall_generations = 30;
cfg.ranking.cache_dir = fullfile(cfg.results_dir, 'ranking_cache');
cfg.ranking.display = 'final';
cfg.ranking.figure_basename = 'figure14_balerma_ranking_objectives';
cfg.ranking.chlorine_figure_basename = ...
    'figure12_balerma_chlorine_ranking_objectives';

cfg.plot.resolution = 450;

% The warm-start table is versioned with the network so a fresh checkout has
% no dependency on dated files elsewhere on the author's computer. Every
% reported result is nevertheless generated by a fresh GA run.
seed_table = readtable(fullfile(network_dir, 'seeds', ...
    'initial_designs.csv'), 'TextType', 'string');
if ~isequal(string(seed_table.LinkID), string(cfg.design_link_ids(:)))
    error('balerma:SeedLinkMismatch', ...
        'Balerma seed-table link IDs or their order do not match the INP file.');
end
for k = 1:numel(cfg.objectives)
    objective_name = cfg.objectives{k};
    cfg.ga.seed_designs.(objective_name) = ...
        seed_table.(objective_name)';
end
end

function ids = read_section_ids(inp_file, section_name)
lines = splitlines(string(fileread(inp_file)));
header = "[" + upper(string(section_name)) + "]";
inside = false;
ids = strings(0, 1);
for k = 1:numel(lines)
    line = strtrim(lines(k));
    if startsWith(line, "[")
        inside = strcmpi(line, header);
        continue;
    end
    if ~inside || strlength(line) == 0 || startsWith(line, ";")
        continue;
    end
    tokens = split(line);
    tokens(tokens == "") = [];
    ids(end + 1, 1) = tokens(1); %#ok<AGROW>
end
ids = cellstr(ids);
end
