function summary=extract_balerma_all_four_pareto_service(result_dir)
%EXTRACT_BALERMA_ALL_FOUR_PARETO_SERVICE Summarize the saved four-source replay.
% Uses exactly the 20 diameter vectors displayed in the R44 comparison.
% This function only reads existing 908-case checkpoints; it does not solve
% hydraulics, chlorine transport, or an optimization problem.
if nargin<1 || isempty(result_dir)
    result_dir=fullfile(fileparts(mfilename('fullpath')), ...
        'results_staci_uniform_0p1_64in_sourceentry_v4');
end
saved=load(fullfile(result_dir,'pareto_cost_branch_hop_top90.mat'),'result');
designs=double(saved.result.designs);
selected=readtable(fullfile(result_dir,'pareto_selected20_indices.csv'));
ids=double(selected.ArchiveIndex(:));
assert(numel(ids)==20 && numel(unique(ids))==20 && ...
    all(ids>=1 & ids<=size(designs,1)));
rows=cell(numel(ids),1);
for k=1:numel(ids)
    id=ids(k);
    file=fullfile(result_dir,'pareto_failure_replay_r44', ...
        'checkpoints',sprintf('point_%04d.mat',id));
    saved_case=load(file,'diameters','all_cases');
    assert(isequal(double(saved_case.diameters(:)'),designs(id,:)), ...
        'Stale Pareto checkpoint %d',id);
    cases=saved_case.all_cases( ...
        string(saved_case.all_cases.ReservoirAvailability)=="all_four",:);
    assert(height(cases)==454 && all(~cases.Nonconvergent) && ...
        nnz(cases.SolverToleranceFallback)==0 && ...
        nnz(cases.EpanetFallback)==0, ...
        'Incomplete four-reservoir replay for Pareto point %d',id);
    water=100*double(cases.DeliveredDemandFraction);
    chlorine=100*double(cases.QualityCompliantDemandFraction);
    [water_worst,wi]=min(water);
    [cl_worst,ci]=min(chlorine);
    rows{k}=table(id,saved.result.cost(id), ...
        saved.result.branch_hop_entropy(id),mean(water),water_worst, ...
        mean(chlorine),cl_worst,string(cases.FailedLinkID(wi)), ...
        "all_four",string(cases.FailedLinkID(ci)),"all_four", ...
        height(cases),nnz(cases.Nonconvergent), ...
        nnz(cases.SolverToleranceFallback),nnz(cases.EpanetFallback), ...
        'VariableNames',{'ArchiveIndex','Cost','BranchHopEntropy', ...
        'WaterMeanPct','WaterWorstPct','ClMeanPct','ClWorstPct', ...
        'WaterWorstPipe','WaterWorstAvailability','ClWorstPipe', ...
        'ClWorstAvailability','FailureCases','NonconvergentScenarios', ...
        'ToleranceFallbackCases','EpanetFallbackCases'});
end
summary=sortrows(vertcat(rows{:}),'ArchiveIndex');
output_dir=fullfile(result_dir,'pareto_failure_replay_all_four');
if ~isfolder(output_dir),mkdir(output_dir);end
writetable(summary,fullfile(output_dir,'pareto_failure_service.csv'));
fprintf('Summarized %d saved Pareto designs, 454 all-four cases each.\n', ...
    height(summary));
end
