function plot_node6_reservoir_pair()
% Two-panel visualization of the saved, inverse-sized node-6 reservoir pair.
here=fileparts(mfilename('fullpath'));
data=load(fullfile(here,'pair_result.mat'),'out');
out=data.out;
ids=["1","2","3","4","5","6"];
xy=[1.8 2.3;-1.8 2.3;1.8 0;-1.8 0;1.8 -2.3;-1.8 -2.3];
pipe_ids=["P1","P4","P7","P6","P2","P3","P8","P5"];
ends=["1","3";"2","4";"4","6";"3","5"; ...
      "1","4";"2","3";"5","6";"3","4"];
label_xy=[2.17 1.15;-2.17 1.15;-2.17 -1.15;2.17 -1.15; ...
          0.82 1.74;-0.82 0.70;0 -2.82;0 -0.46];
label_align={'left','right','right','left','center','center','center','center'};
[found,link_index]=ismember(pipe_ids,string(out.link_ids));
assert(all(found),'Saved physical pipe IDs missing');
changed=abs(diff(out.diameters_mm,1,2))>0.005;
fig=figure('Visible','off','Color','w','Units','centimeters', ...
    'Position',[2 2 39 18]);
t=tiledlayout(fig,1,2,'TileSpacing','compact','Padding','compact');
for k=1:2
    ax=nexttile(t);hold(ax,'on');
    for j=1:8
        [~,aa]=ismember(ends(j,1),ids);[~,bb]=ismember(ends(j,2),ids);
        first=xy(aa,:);last=xy(bb,:);
        plot(ax,[first(1),last(1)],[first(2),last(2)],'k-', ...
            'LineWidth',1.1+1.6*out.diameters_mm(j,k)/100);
        if out.link_flows_m3h(link_index(j),k)<0
            temp=first;first=last;last=temp;
        end
        origin=first+0.40*(last-first);direction=0.16*(last-first);
        quiver(ax,origin(1),origin(2),direction(1),direction(2),0, ...
            'Color','k','LineWidth',1,'MaxHeadSize',1.5);
    end
    % The R6--6 connector has a 1-m length and 1000-mm diameter, so
    % the head at consumer node 6 is effectively the 35-m reservoir head.
    plot(ax,[-1.8,-1.8],[-3.30,-2.3],'-','Color',[0.10 0.35 0.55], ...
        'LineWidth',2.0);
    quiver(ax,-1.8,-3.10,0,0.45,0,'Color',[0.10 0.35 0.55], ...
        'LineWidth',1.4,'MaxHeadSize',1.4);
    scatter(ax,-1.8,-3.36,150,'d','MarkerFaceColor',[0.78 0.91 0.98], ...
        'MarkerEdgeColor',[0.10 0.35 0.55],'LineWidth',1.5);
    text(ax,-1.8,-3.67,'R6: 35 m','FontName','Times New Roman', ...
        'FontSize',11.5,'HorizontalAlignment','center');
    text(ax,-1.8,-4.02,sprintf('inflow %.2f m$^3$/h', ...
        out.reservoir_flow_m3h(k)),'Interpreter','latex', ...
        'FontName','Times New Roman','FontSize',10.5, ...
        'HorizontalAlignment','center');
    for n=1:numel(ids)
        [~,ni]=ismember(ids(n),string(out.node_ids));
        scatter(ax,xy(n,1),xy(n,2),95,[0.15 0.29 0.46],'filled', ...
            'MarkerEdgeColor','k','LineWidth',1);
        text(ax,xy(n,1),xy(n,2)+0.25,char(ids(n)), ...
            'FontName','Times New Roman','FontSize',13, ...
            'HorizontalAlignment','center','FontWeight','bold');
        side=sign(xy(n,1));node_x=xy(n,1)+side*0.40;
        if side<0,alignment='right';else,alignment='left';end
        node_label=sprintf('H=%.2f m\nc=%.3f mg/L', ...
            out.heads_m(ni,k),out.chlorine_mgL(ni,k));
        text(ax,node_x,xy(n,2),node_label,'FontName','Times New Roman', ...
            'FontSize',10.5,'HorizontalAlignment',alignment, ...
            'VerticalAlignment','middle','BackgroundColor','w','Margin',1.2);
    end
    for j=1:8
        if changed(j)
            dlabel=sprintf('$\\mathrm{%s}:~d=\\mathbf{%.2f}\\,mm$', ...
                pipe_ids(j),out.diameters_mm(j,k));
        else
            dlabel=sprintf('$\\mathrm{%s}:~d=%.2f\\,mm$', ...
                pipe_ids(j),out.diameters_mm(j,k));
        end
        qlabel=sprintf('$|Q|=%.2f\\,\\mathrm{m^3/h}$', ...
            abs(out.link_flows_m3h(link_index(j),k)));
        text(ax,label_xy(j,1),label_xy(j,2)+0.15,dlabel, ...
            'Interpreter','latex','FontName','Times New Roman', ...
            'FontSize',11.5,'HorizontalAlignment',label_align{j}, ...
            'VerticalAlignment','bottom','BackgroundColor','w','Margin',0.5);
        text(ax,label_xy(j,1),label_xy(j,2)-0.15,qlabel, ...
            'Interpreter','latex','FontName','Times New Roman', ...
            'FontSize',10.5,'HorizontalAlignment',label_align{j}, ...
            'VerticalAlignment','top','BackgroundColor','w','Margin',0.5);
    end
    title(ax,sprintf('(%c) Design %c: $S_{\\mathrm{Cl}}=%.8f$ nat', ...
        'a'+k-1,'A'+k-1,out.chlorine_entropy_nat(k)), ...
        'Interpreter','latex','FontSize',14,'FontWeight','normal');
    xlim(ax,[-5.0,5.0]);ylim(ax,[-4.30,3.0]);axis(ax,'off');
end
base=fullfile(here,'node6_reservoir_equal_entropy_pair');
exportgraphics(fig,[base '.png'],'Resolution',600);
exportgraphics(fig,[base '.svg'],'ContentType','vector');
close(fig);
end
