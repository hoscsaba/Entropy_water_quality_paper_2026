function run_anytown_cost_entropy
%RUN_ANYTOWN_COST_ENTROPY Recompute the cost--entropy Pareto front.

root = fileparts(mfilename('fullpath'));
addpath(root);
network_dir = fullfile(root, 'networks', 'anytown');
addpath(network_dir);
cfg = network_config(network_dir);
wdn.setup_toolkit(cfg);
if ~exist(cfg.results_dir, 'dir'), mkdir(cfg.results_dir); end
if ~exist(cfg.figures_dir, 'dir'), mkdir(cfg.figures_dir); end

result = wdn.optimize_multiobjective(cfg, ...
    {'cost', 'hydraulic_entropy'});
save(fullfile(cfg.results_dir, 'multiobjective_cost_entropy.mat'), ...
    'result', 'cfg');

point = (1:numel(result.cost))';
summary = table(point, result.cost(:), result.hydraulic_entropy(:), ...
    result.chlorine_concentration(:), result.chlorine_entropy(:), ...
    result.minimum_pressure(:), result.anchor_head_deviation(:), ...
    result.max_constraint_violation(:), 'VariableNames', ...
    {'point','cost','hydraulic_entropy', ...
    'chlorine_concentration_objective','chlorine_entropy', ...
    'minimum_pressure_psi','maximum_anchor_head_deviation_ft', ...
    'maximum_constraint_violation'});
writetable(summary, fullfile(cfg.results_dir, ...
    'multiobjective_cost_entropy.csv'));

wdn.plot_cost_entropy_front(result, cfg, ...
    fullfile(cfg.figures_dir, 'figure7_cost_entropy.png'));
fprintf('Saved %d validated cost--entropy Pareto points.\n', height(summary));
end
