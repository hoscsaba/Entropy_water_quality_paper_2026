function manifest = export_manuscript_tables
%EXPORT_MANUSCRIPT_TABLES Collect the data behind all numerical paper tables.
% The exported CSV files are audit-ready inputs; descriptive tables remain
% maintained directly in LaTeX because they contain no computed values.

root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
output_dir = fullfile(root, 'manuscript', 'generated', 'tables');
if ~isfolder(output_dir), mkdir(output_dir); end

sources = {
    'Tanyimboh objective cross-evaluation', ...
        fullfile(root, 'networks', 'tanyimboh_templeman', 'results_staci', 'cross_evaluation.csv'), ...
        'tanyimboh_cross_evaluation.csv';
    'Anytown objective cross-evaluation', ...
        fullfile(root, 'networks', 'anytown', 'results_staci', 'cross_evaluation.csv'), ...
        'anytown_cross_evaluation.csv';
    'STACI single-objective stopping and CPU time', ...
        fullfile(root, 'supplementary', 'results', 'staci_single_objective_summary.csv'), ...
        'staci_single_objective_summary.csv';
    'Anytown single-pipe stress test', ...
        fullfile(root, 'networks', 'anytown', 'results_staci', 'stress_test.csv'), ...
        'anytown_stress_test.csv';
    'Anytown pressure-driven N-1 service', ...
        fullfile(root, 'networks', 'anytown', 'results_staci', 'pda_service_summary.csv'), ...
        'anytown_pda_service_summary.csv';
    'Anytown pressure-driven N-1 scenarios', ...
        fullfile(root, 'networks', 'anytown', 'results_staci', 'pda_service_scenarios.csv'), ...
        'anytown_pda_service_scenarios.csv';
    'Anytown conditional outage vulnerability', ...
        fullfile(root, 'networks', 'anytown', 'results_staci', 'pda_vulnerability_summary.csv'), ...
        'anytown_pda_vulnerability_summary.csv';
    'Anytown pipe failure criticality', ...
        fullfile(root, 'networks', 'anytown', 'results_staci', 'pda_pipe_criticality.csv'), ...
        'anytown_pda_pipe_criticality.csv';
    'Anytown ranking versus failure impact', ...
        fullfile(root, 'networks', 'anytown', 'results_staci', 'pda_ranking_validation.csv'), ...
        'anytown_pda_ranking_validation.csv';
    'Anytown top-20 rankings', ...
        fullfile(root, 'networks', 'anytown', 'results_staci', 'pipe_rankings_top20.csv'), ...
        'anytown_pipe_rankings_top20.csv';
    'Balerma objective cross-evaluation', ...
        fullfile(root, 'networks', 'balerma', 'results_staci', 'cross_evaluation.csv'), ...
        'balerma_cross_evaluation.csv';
    'Balerma single-pipe stress test', ...
        fullfile(root, 'networks', 'balerma', 'results_staci', 'stress_test.csv'), ...
        'balerma_stress_test.csv';
    'Balerma pressure-driven N-1 service', ...
        fullfile(root, 'networks', 'balerma', 'results_staci', 'pda_service_summary.csv'), ...
        'balerma_pda_service_summary.csv';
    'Balerma pressure-driven N-1 scenarios', ...
        fullfile(root, 'networks', 'balerma', 'results_staci', 'pda_service_scenarios.csv'), ...
        'balerma_pda_service_scenarios.csv';
    'Balerma conditional outage vulnerability', ...
        fullfile(root, 'networks', 'balerma', 'results_staci', 'pda_vulnerability_summary.csv'), ...
        'balerma_pda_vulnerability_summary.csv';
    'Balerma pipe failure criticality', ...
        fullfile(root, 'networks', 'balerma', 'results_staci', 'pda_pipe_criticality.csv'), ...
        'balerma_pda_pipe_criticality.csv';
    'Balerma ranking versus failure impact', ...
        fullfile(root, 'networks', 'balerma', 'results_staci', 'pda_ranking_validation.csv'), ...
        'balerma_pda_ranking_validation.csv';
    'Balerma top-45 rankings', ...
        fullfile(root, 'networks', 'balerma', 'results_staci', 'pipe_rankings_top45.csv'), ...
        'balerma_pipe_rankings_top45.csv';
    'Full-optimum cross-effects', ...
        fullfile(root, 'results_staci', 'objective_relationships', 'full_optimum_cross_effects.csv'), ...
        'full_optimum_cross_effects.csv';
    'Ranking-trajectory correlations', ...
        fullfile(root, 'results_staci', 'objective_relationships', 'ranking_trajectory_correlations.csv'), ...
        'ranking_trajectory_correlations.csv'};

description = strings(size(sources, 1), 1);
source = strings(size(sources, 1), 1);
exported = strings(size(sources, 1), 1);
for k = 1:size(sources, 1)
    description(k) = string(sources{k, 1});
    source(k) = erase(string(sources{k, 2}), string(root) + filesep);
    if ~isfile(sources{k, 2})
        error('paper:MissingTableSource', ...
            'Missing table source: %s', sources{k, 2});
    end
    destination = fullfile(output_dir, sources{k, 3});
    copyfile(sources{k, 2}, destination, 'f');
    exported(k) = erase(string(destination), string(root) + filesep);
end

source = replace(source, filesep, '/');
exported = replace(exported, filesep, '/');

write_tanyimboh_reference_table(output_dir);
manifest = table(description, source, exported);
writetable(manifest, fullfile(output_dir, 'table_source_manifest.csv'));
fprintf('Manuscript table data exported to %s\n', output_dir);
end

function write_tanyimboh_reference_table(output_dir)
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(root);
verified = wdn.verify_tanyimboh_reference();
link = ["1-3";"1-4";"2-3";"2-4";"3-4";"3-5";"4-6";"5-6";"Entropy S/K"];
case_a_reference = [verified.reference_flows(1,:)';verified.reference_entropy(1)];
case_a_present = [verified.optimized_flows(1,:)';verified.entropy(1)];
case_b_reference = [verified.reference_flows(2,:)';verified.reference_entropy(2)];
case_b_present = [verified.optimized_flows(2,:)';verified.entropy(2)];
values = table(link, case_a_reference, case_a_present, ...
    abs(case_a_reference-case_a_present), case_b_reference, case_b_present, ...
    abs(case_b_reference-case_b_present), 'VariableNames', ...
    {'Link','CaseAReference','CaseAPresent','CaseAAbsoluteDifference', ...
    'CaseBReference','CaseBPresent','CaseBAbsoluteDifference'});
writetable(values, fullfile(output_dir, ...
    'tanyimboh_reference_validation.csv'));
end
